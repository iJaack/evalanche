export class SolanaPolicyDenial extends Error {
  constructor(readonly reason: SolanaDenyReason, detail: string, readonly instructionIndex?: number) {
    super(`${reason}: ${detail}`);
    this.name = 'SolanaPolicyDenial';
  }
}
export function deny(reason: SolanaDenyReason, detail: string, index?: number): never {
  throw new SolanaPolicyDenial(reason, detail, index);
}
